import * as NodeFileSystem from "@effect/platform-node-shared/NodeFileSystem";
import * as NodePath from "@effect/platform-node-shared/NodePath";
import { it as effectIt } from "@effect/vitest";
import { Effect, Fiber, Layer, Predicate } from "effect";
import { existsSync, statSync } from "node:fs";
import { chmod, readFile, readdir } from "node:fs/promises";
import path from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { build, createAnhur, isAnhurBuildError } from "../../src/build";
import {
  contentHash,
  type OutputFile,
  type PlanRevision,
} from "../../src/engine/codegen";
import { MANIFEST_FILE } from "../../src/engine/output-files";
import { OutputWriter } from "../../src/engine/output.service";
import { createProject, type TestProject } from "../fixtures/temp-project";

// Failure modes these tests are for:
// 1. After one build that could not write (no permission, full disk), a
//    changed document keeps its old generated module in every later build.
// 2. An interrupted build goes on writing after it gave the output lock
//    back, so the next build (or another process) writes at the same time.
// 3. A bug in the engine is reported as a problem with the output folder.
// 4. A folder with only temp files of a killed first build is refused for
//    ever; a folder of the user is taken for old output.

const HEADER = "// generated by @anhur/core\n";
const CONFIG = `
import { defineCollection, defineConfig, schema as s } from "@anhur/core";
export default defineConfig({
  content: [defineCollection({ name: "notes", directory: "notes", include: "**/*.md", schema: s.object({ title: s.string() }) })],
});
`;

const projects: TestProject[] = [];
afterEach(async () => {
  for (const project of projects.splice(0)) await project.remove();
});

/** A user with every permission (root in a container) is not stopped by chmod. */
const isRoot = process.getuid?.() === 0;

const WriterLive = OutputWriter.layer.pipe(
  Layer.provide(Layer.mergeAll(NodeFileSystem.layer, NodePath.layer)),
);

function file(
  filePath: string,
  text: string,
  onContents?: () => void,
): OutputFile {
  return {
    path: filePath,
    hash: contentHash(text),
    size: Buffer.byteLength(text),
    contents: () => {
      onContents?.();
      return text;
    },
  };
}

function revision(): PlanRevision {
  return { kind: "plan-revision" };
}

/** Files below `dir` (POSIX paths), without the manifest. */
async function filesIn(dir: string): Promise<string[]> {
  const entries = await readdir(dir, { recursive: true });
  return entries
    .filter((entry) => statSync(path.join(dir, entry)).isFile())
    .map((entry) => entry.split(path.sep).join("/"))
    .filter((entry) => entry !== MANIFEST_FILE)
    .sort();
}

async function manifestOf(dir: string): Promise<Map<string, string>> {
  const parsed: unknown = JSON.parse(
    await readFile(path.join(dir, MANIFEST_FILE), "utf8"),
  );
  const files =
    Predicate.isObject(parsed) &&
    "files" in parsed &&
    Predicate.isObject(parsed.files)
      ? parsed.files
      : {};
  return new Map(
    Object.entries(files).map(([name, hash]) => [name, String(hash)]),
  );
}

describe("a build that could not write", () => {
  it.skipIf(isRoot)(
    "is made good by the next build of the session, and of a new session",
    async () => {
      const project = await createProject({
        "anhur.config.ts": CONFIG,
        "notes/a.md": "---\ntitle: Old title\n---\n",
      });
      projects.push(project);
      const session = createAnhur({ rootDir: project.dir });
      const documents = project.path(".anhur/generated/documents/notes");
      try {
        await session.build();
        const [moduleOfA] = await readdir(documents);
        expect(moduleOfA).toMatch(/^a-/);

        // An edit that keeps the size of the module, and a new document.
        await project.write("notes/a.md", "---\ntitle: New title\n---\n");
        await project.write("notes/b.md", "---\ntitle: B\n---\n");
        await chmod(documents, 0o555);
        const failure = await session
          .build()
          .then(
            () => undefined,
            (cause: unknown) => cause,
          )
          .finally(() => chmod(documents, 0o755));
        expect(
          isAnhurBuildError(failure) &&
            failure.diagnostics.map((diagnostic) => diagnostic.code),
        ).toEqual(["publish-failed"]);

        await session.build();
        expect(
          await readFile(path.join(documents, moduleOfA ?? ""), "utf8"),
        ).toContain('"title":"New title"');
        expect(await readdir(documents)).toHaveLength(2);
      } finally {
        await session.close();
      }
      const fresh = await build({ rootDir: project.dir });
      expect(fresh.written).toEqual([]);
      const listed = await manifestOf(fresh.outputDir);
      for (const name of await filesIn(fresh.outputDir)) {
        const text = await readFile(path.join(fresh.outputDir, name), "utf8");
        expect(listed.get(name), name).toBe(contentHash(text));
      }
    },
  );
});

describe("OutputWriter", () => {
  const write = Effect.fn("test.write")(function* (
    out: string,
    files: readonly OutputFile[],
  ) {
    const writer = yield* OutputWriter;
    return yield* writer.write(out, files, revision());
  });

  effectIt.live(
    "ends an interrupted write before the lock is given back, with a manifest that is true",
    () =>
      Effect.gen(function* () {
        const project = yield* Effect.tryPromise(() => createProject({}));
        projects.push(project);
        const out = project.path("out");
        const body = "x".repeat(20_000);
        let started = 0;
        let reachHalfway = () => {};
        const halfway = new Promise<void>((resolve) => {
          reachHalfway = resolve;
        });
        const files = Array.from({ length: 400 }, (_, index) =>
          file(
            `documents/d${index}.js`,
            `${HEADER}export default ${index}; // ${body}\n`,
            () => {
              started += 1;
              if (started === 40) reachHalfway();
            },
          ),
        );
        const writer = yield* OutputWriter;
        const fiber = yield* Effect.forkChild(
          Effect.scoped(
            Effect.gen(function* () {
              yield* writer.lock(out);
              return yield* write(out, files);
            }),
          ),
        );
        yield* Effect.tryPromise(() => halfway);
        yield* Fiber.interrupt(fiber);
        // The build ended: what it left is what stays.
        const startedAtEnd = started;
        const lockedAtEnd = existsSync(`${out}.lock`);
        const filesAtEnd = yield* Effect.tryPromise(() => filesIn(out));
        // Time for a writer that did not stop to show itself.
        yield* Effect.sleep("250 millis");
        expect(lockedAtEnd).toBe(false);
        expect(startedAtEnd).toBeLessThan(400);
        expect(started).toBe(startedAtEnd);
        expect(yield* Effect.tryPromise(() => filesIn(out))).toEqual(
          filesAtEnd,
        );
        expect(filesAtEnd).toHaveLength(startedAtEnd);

        const listed = yield* Effect.tryPromise(() => manifestOf(out));
        expect(listed.size).toBe(400);
        const written = [...listed].filter(([, hash]) => hash !== "");
        expect(written.map(([name]) => name).sort()).toEqual(filesAtEnd);
        for (const [name, hash] of written) {
          const text = yield* Effect.tryPromise(() =>
            readFile(path.join(out, name), "utf8"),
          );
          expect(contentHash(text), name).toBe(hash);
        }
      }).pipe(Effect.provide(WriterLive)),
  );

  effectIt.live(
    "reports a problem with the folder as publish-failed and a bug as a defect",
    () =>
      Effect.gen(function* () {
        const project = yield* Effect.tryPromise(() => createProject({}));
        projects.push(project);
        const out = project.path("out");

        const refused = yield* Effect.flip(
          write(out, [file("../outside.js", HEADER)]),
        );
        expect(refused.diagnostics).toMatchObject([{ code: "publish-failed" }]);

        const bug = file("index.js", HEADER, () => {
          throw new TypeError("plan.render is not a function");
        });
        const defect = yield* write(out, [bug]).pipe(
          Effect.as(undefined),
          Effect.catchDefect((cause) => Effect.succeed(cause)),
        );
        expect(defect).toBeInstanceOf(TypeError);
      }).pipe(Effect.provide(WriterLive)),
  );

  effectIt.live(
    "takes a folder with only temp files of a killed first build, not a folder of the user",
    () =>
      Effect.gen(function* () {
        const project = yield* Effect.tryPromise(() =>
          createProject({
            [`killed/.${MANIFEST_FILE}.0a1b2c3d.tmp`]: "{",
            "lib/index.js": `${HEADER}export {};\n`,
            "lib/util/helpers.js": "// my own helper\n",
          }),
        );
        projects.push(project);
        const writer = yield* OutputWriter;
        yield* writer.checkOwnership(project.path("killed"));
        const refused = yield* Effect.flip(
          writer.checkOwnership(project.path("lib")),
        );
        expect(refused.diagnostics).toMatchObject([{ code: "output-unsafe" }]);
      }).pipe(Effect.provide(WriterLive)),
  );
});
