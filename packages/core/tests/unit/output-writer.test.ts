import { mkdirSync, mkdtempSync, rmSync, statSync, symlinkSync } from "node:fs";
import {
  chmod,
  mkdir,
  readFile,
  readdir,
  rm,
  symlink,
  writeFile,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { Predicate } from "effect";
import { afterEach, describe, expect, it } from "vitest";
import {
  contentHash,
  type OutputFile,
  type PlanRevision,
} from "../../src/engine/codegen";
import {
  adoptLegacy,
  createOutputState,
  MANIFEST_FILE,
  OutputWriteError,
  writeOutputFiles,
  type OutputState,
} from "../../src/engine/output-files";
import { createProject, type TestProject } from "../fixtures/temp-project";

// Failure modes these tests are for:
// 1. The manifest has the hash of a text that is not on disk (the write
//    failed, or was stopped): every later build takes the old file for
//    current when its size is the same.
// 2. A stopped write goes on writing.
// 3. A symbolic link in the output folder makes the writer change or
//    delete files of the user.
// 4. A folder of the user that has a generated-looking index.js is taken
//    for output of an older Anhur and its files are deleted.
// 5. Temp files of a killed build stay for ever, and block the adoption
//    of an old output folder.
// 6. A file that could not be deleted is forgotten: no build deletes it.

const HEADER = "// generated by @anhur/core\n";

const projects: TestProject[] = [];
afterEach(async () => {
  for (const project of projects.splice(0)) await project.remove();
});

/** False where the platform or the user may not make symbolic links. */
function canLink(): boolean {
  const dir = mkdtempSync(path.join(tmpdir(), "anhur-link-"));
  try {
    mkdirSync(path.join(dir, "target"));
    symlinkSync(path.join(dir, "target"), path.join(dir, "link"));
    return true;
  } catch {
    return false;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

/** A user with every permission (root in a container) is not stopped by chmod. */
const isRoot = process.getuid?.() === 0;

function file(
  filePath: string,
  text: string,
  onContents?: () => void,
): OutputFile {
  return {
    path: filePath,
    hash: contentHash(text),
    size: Buffer.byteLength(text),
    contents: () => {
      onContents?.();
      return text;
    },
  };
}

function write(
  dir: string,
  files: readonly OutputFile[],
  state: OutputState = createOutputState(),
  signal?: AbortSignal,
) {
  // A new plan every time: the writer never takes the short way out.
  const revision: PlanRevision = { kind: "plan-revision" };
  return writeOutputFiles(dir, files, revision, state, Date.now(), signal);
}

async function outputProject(files: {
  readonly [file: string]: string;
}): Promise<TestProject> {
  const project = await createProject(files);
  projects.push(project);
  return project;
}

/** Files below `dir` (POSIX paths), without the manifest. */
async function filesIn(dir: string): Promise<string[]> {
  const entries = await readdir(dir, { recursive: true });
  return entries
    .filter((entry) => statSync(path.join(dir, entry)).isFile())
    .map((entry) => entry.split(path.sep).join("/"))
    .filter((entry) => entry !== MANIFEST_FILE)
    .sort();
}

async function manifestOf(dir: string): Promise<Map<string, string>> {
  const parsed: unknown = JSON.parse(
    await readFile(path.join(dir, MANIFEST_FILE), "utf8"),
  );
  const files =
    Predicate.isObject(parsed) &&
    "files" in parsed &&
    Predicate.isObject(parsed.files)
      ? parsed.files
      : {};
  return new Map(
    Object.entries(files).map(([name, hash]) => [name, String(hash)]),
  );
}

/**
 * The manifest says nothing false: a hash it has is the hash of the file
 * on disk, and every file on disk is listed.
 */
async function expectTrueManifest(dir: string): Promise<void> {
  const listed = await manifestOf(dir);
  for (const [name, hash] of listed) {
    if (hash === "") continue;
    const text = await readFile(path.join(dir, name), "utf8");
    expect(contentHash(text), `hash of ${name}`).toBe(hash);
  }
  for (const name of await filesIn(dir)) {
    expect(listed.has(name), `${name} is listed`).toBe(true);
  }
}

describe("writeOutputFiles", () => {
  it("records no hash for a file it did not write, so the next build writes it", async () => {
    const project = await outputProject({});
    const before = `${HEADER}export default "Old title";\n`;
    const after = `${HEADER}export default "New title";\n`;
    expect(Buffer.byteLength(after)).toBe(Buffer.byteLength(before));
    // A build that adds a file and changes another one.
    const plan = (onChange?: () => void) => [
      file("a.js", after, onChange),
      file("added.js", `${HEADER}export default 1;\n`),
      file("index.js", HEADER),
    ];
    // The same session, and a new one, write the file after a failed write.
    for (const sameSession of [true, false]) {
      const dir = project.path(sameSession ? "same" : "new");
      const state = createOutputState();
      await write(dir, [file("a.js", before), file("index.js", HEADER)], state);
      const failed = write(
        dir,
        plan(() => {
          throw new Error("the disk is full");
        }),
        state,
      );
      await expect(failed).rejects.toThrow("the disk is full");
      expect(await readFile(path.join(dir, "a.js"), "utf8")).toBe(before);
      await expectTrueManifest(dir);

      await write(dir, plan(), sameSession ? state : createOutputState());
      expect(await readFile(path.join(dir, "a.js"), "utf8")).toBe(after);
      await expectTrueManifest(dir);
    }
  });

  it("stops at the abort signal: the files in work are finished, no file is started, the manifest is true", async () => {
    const project = await outputProject({});
    const dir = project.path("out");
    const controller = new AbortController();
    let started = 0;
    const count = () => {
      started += 1;
      if (started === 20) controller.abort();
    };
    const plan = (onContents?: () => void) => [
      ...Array.from({ length: 200 }, (_, index) =>
        file(
          `documents/d${index}.js`,
          `${HEADER}export default ${index};\n`,
          onContents,
        ),
      ),
      file("index.js", HEADER),
    ];
    const state = createOutputState();
    await expect(
      write(dir, plan(count), state, controller.signal),
    ).rejects.toThrow(OutputWriteError);
    expect(started).toBe(20);
    expect(await filesIn(dir)).toHaveLength(20);
    const listed = await manifestOf(dir);
    expect(listed.size).toBe(201);
    expect([...listed.values()].filter((hash) => hash !== "")).toHaveLength(20);
    await expectTrueManifest(dir);

    const next = await write(dir, plan(), state);
    expect(next.written).toHaveLength(181);
    expect(await filesIn(dir)).toHaveLength(201);
    await expectTrueManifest(dir);
  });

  it.skipIf(!canLink())(
    "does not write or delete through a link that leads out of the output folder",
    async () => {
      const mine = "// my own code\n";
      const project = await outputProject({
        "src/index.js": mine,
        "src/a.js": mine,
      });
      const dir = project.path("out");
      await write(dir, [
        file("index.js", HEADER),
        file("documents/a.js", `${HEADER}export default 1;\n`),
      ]);
      await rm(path.join(dir, "documents"), { recursive: true });
      await symlink(project.path("src"), path.join(dir, "documents"));

      // `documents/a.js` is listed, but the file there now is the user's.
      const refusedDelete = await write(dir, [file("index.js", HEADER)]).then(
        () => undefined,
        (cause: unknown) => cause,
      );
      expect(refusedDelete).toBeInstanceOf(OutputWriteError);
      expect(refusedDelete).toMatchObject({
        path: path.join(dir, "documents", "a.js"),
      });
      const refusedWrite = await write(dir, [
        file("index.js", HEADER),
        file("documents/a.js", `${HEADER}export default 1;\n`),
        file("documents/index.js", `${HEADER}export default 2;\n`),
      ]).then(
        () => undefined,
        (cause: unknown) => cause,
      );
      expect(refusedWrite).toMatchObject({
        _tag: "OutputWriteError",
        path: path.join(dir, "documents", "index.js"),
      });
      expect(await project.read("src/index.js")).toBe(mine);
      expect(await project.read("src/a.js")).toBe(mine);
      expect(await filesIn(project.path("src"))).toEqual(["a.js", "index.js"]);
    },
  );

  it("removes temp files of a killed build, and nothing else it did not write", async () => {
    const project = await outputProject({});
    const dir = project.path("out");
    const plan = [
      file("index.js", HEADER),
      file("documents/a.js", `${HEADER}export default 1;\n`),
    ];
    await write(dir, plan);
    await writeFile(path.join(dir, "documents", ".a.js.0a1b2c3d.tmp"), "half");
    await writeFile(path.join(dir, `.${MANIFEST_FILE}.deadbeef.tmp`), "{");
    await writeFile(path.join(dir, "documents", "notes.txt"), "mine");
    await writeFile(path.join(dir, ".mine.tmp"), "mine");
    await write(dir, plan);
    expect(await filesIn(dir)).toEqual([
      ".mine.tmp",
      "documents/a.js",
      "documents/notes.txt",
      "index.js",
    ]);
  });

  it.skipIf(isRoot)(
    "keeps a file it could not delete in the manifest and deletes it in a later build",
    async () => {
      const project = await outputProject({});
      const dir = project.path("out");
      const state = createOutputState();
      const kept = [
        file("index.js", HEADER),
        file("documents/a.js", `${HEADER}export default 1;\n`),
      ];
      await write(
        dir,
        [...kept, file("documents/b.js", `${HEADER}export default 2;\n`)],
        state,
      );
      await chmod(path.join(dir, "documents"), 0o555);
      try {
        const blocked = await write(dir, kept, state);
        expect(blocked.removed).toEqual([]);
        expect((await manifestOf(dir)).has("documents/b.js")).toBe(true);
      } finally {
        await chmod(path.join(dir, "documents"), 0o755);
      }
      const later = await write(dir, kept, state);
      expect(later.removed).toEqual([path.join(dir, "documents", "b.js")]);
      expect(await filesIn(dir)).toEqual(["documents/a.js", "index.js"]);
      await expectTrueManifest(dir);
    },
  );
});

describe("adoptLegacy", () => {
  it("takes a folder with the files an older Anhur wrote, also after a killed build", async () => {
    const project = await outputProject({
      "out/index.js": `${HEADER}export {};\n`,
      "out/index.d.ts": HEADER,
      "out/.keep": "",
      "out/allPosts.js": HEADER,
      "out/getPost.js": HEADER,
      "out/documents/posts/default__hello%20world.js": HEADER,
      "out/search/orama.json": "{}",
      [`out/.${MANIFEST_FILE}.0a1b2c3d.tmp`]: "{",
    });
    const dir = project.path("out");
    const adopted = await adoptLegacy(dir);
    expect([...(adopted?.files.keys() ?? [])].sort()).toEqual([
      ".keep",
      "allPosts.js",
      "documents/posts/default__hello%20world.js",
      "getPost.js",
      "index.d.ts",
      "index.js",
      "search/orama.json",
    ]);
    const index = file("index.js", `${HEADER}export {};\n`);
    const result = await write(dir, [index]);
    expect(result.removed).toHaveLength(6);
    expect(await filesIn(dir)).toEqual(["index.js"]);
  });

  it("does not take a folder with files an older Anhur never wrote", async () => {
    const project = await outputProject({
      "lib/index.js": `${HEADER}export {};\n`,
      "lib/util/helpers.js": "// my own helper\n",
      "config/index.js": `${HEADER}export {};\n`,
      "config/settings.json": "{}",
    });
    expect(await adoptLegacy(project.path("lib"))).toBe(undefined);
    expect(await adoptLegacy(project.path("config"))).toBe(undefined);
    await mkdir(project.path("empty"));
    expect(await adoptLegacy(project.path("empty"))).toBe(undefined);
  });
});
